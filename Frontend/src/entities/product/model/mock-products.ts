function buildDescription(
  product: Omit<Product, 'images' | 'description' | 'shortDescription'>,
): string {
  const skin = product.skinTypes.join(', ')
  const scent = product.fragranceFree ? 'Fragrance-free.' : 'Lightly scented.'
  return `${product.name} from ${product.brand}'s ${product.line} line is a ${product.formatKey.toLowerCase()} (${product.sizeLabel}) created for ${skin} skin. ${scent}`
}

